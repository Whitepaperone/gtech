'use strict';

const database = require('../config/database');

const ITEM_SQL = `
SELECT I.UNIT AS UNIT, I.PURCHASEPRICE AS PRICE, I.PURCHASECURR AS CURRUNIT
FROM ITEM I WHERE I.CODE = ?
`;

// Keep each occurrence: the same material can belong to multiple OUT FINs.
const BOM_SQL = `
WITH RECURSIVE X AS (
    SELECT P.IINDEX, CAST(P.LINENO AS VARCHAR(4096)) AS LINENO,
        CAST(P.IINDEX AS VARCHAR(4096)) AS BOMPATH,
        CAST(NULL AS VARCHAR(4096)) AS PARENTPATH,
        P.PARENTCODE, P.COMPONENTCODE, P.PARENTDEGREE,
        P.COMPDEGREE AS DEGREE,
        CAST(P.QTY AS DOUBLE PRECISION) / NULLIF(P.PARENTQTY, 0) AS QTY,
        P.UNIT, 1 AS ILEVEL
    FROM PARTLIST P
    WHERE P.PARENTCODE = ? AND P.PIINDEX = ?
        AND P.PARENTDEGREE = ? AND P.USEDEGREE >= 0
    UNION ALL
    SELECT P.IINDEX, CAST(X.LINENO || P.LINENO AS VARCHAR(4096)),
        CAST(X.BOMPATH || '/' || P.IINDEX AS VARCHAR(4096)),
        X.BOMPATH, P.PARENTCODE, P.COMPONENTCODE, P.PARENTDEGREE,
        P.COMPDEGREE,
        CAST(P.QTY AS DOUBLE PRECISION) / NULLIF(P.PARENTQTY, 0),
        P.UNIT, X.ILEVEL + 1
    FROM PARTLIST P
    JOIN X ON P.PARENTCODE = X.COMPONENTCODE AND P.PARENTDEGREE = X.DEGREE
    WHERE P.PIINDEX = 0 AND P.USEDEGREE = 1
)
SELECT X.IINDEX AS IINDEX, X.ILEVEL AS ILEVEL,
    X.COMPONENTCODE AS ITEMCODE, X.PARENTCODE AS PARENTCODE,
    X.PARENTDEGREE AS PARENTDEGREE, X.DEGREE AS DEGREE,
    I.TYPE AS TYPE, I.NAME AS ITEMNAME, I.DESCRIPTION AS DESCRIPTION,
    X.QTY AS QTY, X.UNIT AS UNIT, X.LINENO AS LINENO,
    X.BOMPATH AS BOMPATH, X.PARENTPATH AS PARENTPATH
FROM X JOIN ITEM I ON X.COMPONENTCODE = I.CODE
ORDER BY X.LINENO, X.BOMPATH
`;

async function findBom({ CODE, PIINDEX = 0, PARENTDEGREE = 0 }) {
  const items = await database.query(ITEM_SQL, [CODE]);
  if (!items.length) return null;
  const rows = await database.query(BOM_SQL, [CODE, PIINDEX, PARENTDEGREE]);
  return { ITEM: items[0], DATA: rows.map(row => ({ ...row, CODE })) };
}

module.exports = { findBom, ITEM_SQL, BOM_SQL };
